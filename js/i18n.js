  var lang = 'ru';

  function t(key, vars) {
    var s = (DICT[lang] && DICT[lang][key]) || DICT.ru[key];
    if (s === undefined) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] !== undefined ? String(vars[k]) : m; });
    return s;
  }

  /* «асык / асыка / асыков» — по-казахски форма не меняется. */
  function asyks(n) {
    if (lang === 'kk') return 'асық';
    var m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return 'асык';
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'асыка';
    return 'асыков';
  }

  /* Проставляет тексты во всех элементах с data-i18n / data-i18n-aria. */
  function apply(root) {
    var scope = root || document;
    document.documentElement.lang = lang;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  }

  window.AsykI18n = {
    t: t,
    asyks: asyks,
    apply: apply,
    lang: function () { return lang; },
    setLang: function (l) { if (DICT[l]) lang = l; apply(); },
    keys: function (l) { return Object.keys(DICT[l || 'ru']); }
  };
